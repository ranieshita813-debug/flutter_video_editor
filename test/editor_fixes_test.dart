import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:flutter_video_editor/core/models/project_model.dart';
import 'package:flutter_video_editor/core/services/whisper_service.dart';
import 'package:flutter_video_editor/features/editor/controllers/editor_controller.dart';
import 'package:flutter_video_editor/features/editor/widgets/timeline.dart';

class _FakeWhisperService extends WhisperService {
  _FakeWhisperService(this.cues);
  final List<CaptionCue> cues;

  @override
  Future<List<CaptionCue>> transcribeAudio({
    required String audioFilePath,
    String model = 'whisper-large-v3',
    String? language,
  }) async {
    return cues;
  }
}

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  group('Editor Fixes Unit Tests', () {
    test('addMediaClip delegates audio files to addAudioTrack', () {
      final controller = EditorController();
      expect(controller.project.clips.isEmpty, isTrue);

      controller.addMediaClip('music_track.mp3');

      expect(controller.project.clips.length, equals(1));
      final clip = controller.project.clips.first;
      expect(clip.clipType, equals(ClipType.audio));
      expect(clip.layerIndex, equals(1));
      expect(clip.sourcePath, equals('music_track.mp3'));
    });

    test('addMediaClip adds video files to main track', () {
      final controller = EditorController();
      controller.addMediaClip('video_clip.mp4');

      expect(controller.project.clips.length, equals(1));
      final clip = controller.project.clips.first;
      expect(clip.clipType, equals(ClipType.video));
      expect(clip.layerIndex, equals(0));
    });

    test('generateWhisperCaptions clamps captions to main clip timeline duration', () async {
      final controller = EditorController();

      // Main video clip from 0s to 10s on layer 0
      final mainClip = TimelineClip(
        id: 'main_video_1',
        label: 'Main Video',
        start: Duration.zero,
        end: const Duration(seconds: 10),
        clipType: ClipType.video,
        layerIndex: 0,
        sourcePath: 'video.mp4',
      );
      controller.addClip(mainClip);

      // Cues generated by Whisper (0s-4s, 8s-12s, 15s-20s)
      final fakeCues = <CaptionCue>[
        CaptionCue(
          id: 'cue_1',
          start: Duration.zero,
          end: const Duration(seconds: 4),
          text: 'Hello world',
        ),
        CaptionCue(
          id: 'cue_2',
          start: const Duration(seconds: 8),
          end: const Duration(seconds: 12),
          text: 'Spanning beyond main clip',
        ),
        CaptionCue(
          id: 'cue_3',
          start: const Duration(seconds: 15),
          end: const Duration(seconds: 20),
          text: 'Completely outside main clip',
        ),
      ];

      final fakeWhisper = _FakeWhisperService(fakeCues);

      await controller.generateWhisperCaptions(
        audioFilePath: 'video.mp4',
        whisperService: fakeWhisper,
      );

      final captionClips = controller.project.clips
          .where((c) => c.clipType == ClipType.caption)
          .toList();

      // cue_3 should be completely dropped, cue_2 clamped to 10s end
      expect(captionClips.length, equals(2));
      expect(captionClips[0].start, equals(Duration.zero));
      expect(captionClips[0].end, equals(const Duration(seconds: 4)));

      expect(captionClips[1].start, equals(const Duration(seconds: 8)));
      expect(captionClips[1].end, equals(const Duration(seconds: 10)));
    });

    testWidgets('TimelineWidget renders selected clip with yellow border color', (tester) async {
      final controller = EditorController();
      final clip = TimelineClip(
        id: 'video_1',
        label: 'Test Clip',
        start: Duration.zero,
        end: const Duration(seconds: 5),
        clipType: ClipType.video,
        layerIndex: 0,
      );
      controller.addClip(clip);
      controller.selectClip('video_1');

      final multiOn = ValueNotifier<bool>(false);
      final multi = ValueNotifier<Set<String>>({});

      await tester.pumpWidget(
        MaterialApp(
          home: Scaffold(
            body: TimelineWidget(
              editor: controller,
              multiOn: multiOn,
              multi: multi,
              onClearMulti: () {},
            ),
          ),
        ),
      );

      await tester.pumpAndSettle(const Duration(seconds: 1));

      final containerFinder = find.byWidgetPredicate((widget) {
        if (widget is Container && widget.foregroundDecoration is BoxDecoration) {
          final deco = widget.foregroundDecoration as BoxDecoration;
          if (deco.border is Border) {
            final border = deco.border as Border;
            return border.top.color == const Color(0xFFFFD700);
          }
        }
        return false;
      });

      expect(containerFinder, findsAtLeastNWidgets(1));
    });
  });
}
